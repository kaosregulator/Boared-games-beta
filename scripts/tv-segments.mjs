/**
 * Turns the tapes' episode sheets (captions matched to show transcripts) into
 * the guide's segment table, keyed by tape file name.
 *
 *   node scripts/tv-segments.mjs /mnt/project-files/tv-captions src/tv/lineups/tapeSegments.ts
 *
 * Each <tape>.episodes.json is a list of
 *   { start, end, kind: 'show' | 'commercial' | 'bumper' | 'promo', show, episode }
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dir, out] = process.argv.slice(2);

function title(row) {
  if (row.kind === 'commercial') return 'Commercial break';
  const parts = [row.show, row.episode].filter(Boolean);
  if (parts.length) return parts.join(' · ');
  return row.kind === 'show' ? 'Cartoon' : 'Station break';
}

const table = {};
for (const name of readdirSync(dir).filter(n => n.endsWith('.episodes.json')).sort()) {
  const rows = JSON.parse(readFileSync(join(dir, name), 'utf8')).sort((a, b) => a.start - b.start);
  const segs = [];
  for (const row of rows) {
    const seg = {
      at: Math.round(row.start),
      kind: row.kind === 'show' ? 'show' : row.kind === 'commercial' ? 'ads' : 'bumper',
      title: title(row),
    };
    const last = segs[segs.length - 1];
    if (last && last.kind === seg.kind && last.title === seg.title) continue;
    segs.push(seg);
  }
  table[`${name.slice(0, -'.episodes.json'.length)}.mp4`] = segs;
}

const body = Object.entries(table)
  .map(([file, segs]) => `  ${JSON.stringify(file)}: [\n${segs.map(s => `    ${JSON.stringify(s)},`).join('\n')}\n  ],`)
  .join('\n');
writeFileSync(
  out,
  `// Generated by scripts/tv-segments.mjs from the tapes' episode sheets. Do not edit by hand.\n` +
    `import type { Segment } from './archiveBlocks';\n\n` +
    `export const TAPE_SEGMENTS: Record<string, Segment[]> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(table).length} tapes -> ${out}`);
